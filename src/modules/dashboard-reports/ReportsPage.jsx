import React from 'react';
import { useNavigate } from 'react-router-dom';
import {
  FileText,
  Printer,
  Code2,
  FileSearch
} from 'lucide-react';
import { useApp } from '../../context/AppContext';
import Button from '../../components/Button';
import PageHeader from '../../components/PageHeader';
import EmptyState from '../../components/EmptyState';

export const ReportsPage = () => {
  const {
    resumeFile,
    resumeText,
    analysisResults,
    matchingResults,
    skillAnalysisResults
  } = useApp();

  const navigate = useNavigate();

  if (!resumeText) {
    return (
      <div>
        <PageHeader
          title="Consolidated Resume Report"
          description="Exportable career dossier aggregating ATS audit scores, job compatibility, and improvement steps."
          badge="Module 7"
          icon={FileText}
        />
        <EmptyState
          icon={FileSearch}
          title="No Resume Active for Reporting"
          description="Upload a candidate resume and run AI analysis to generate a complete printable dossier."
          actionLabel="Upload Resume"
          onAction={() => navigate('/upload-resume')}
        />
      </div>
    );
  }

  const handlePrint = () => {
    window.print();
  };

  return (
    <div>
      <PageHeader
        title="Comprehensive Analysis Report"
        description="Full-spectrum resume audit and career alignment report ready for candidate presentation or PDF export."
        badge="Module 7: Reports"
        icon={FileText}
        actions={
          <div style={{ display: 'flex', gap: '8px' }}>
            <Button variant="outline" icon={Printer} onClick={handlePrint}>
              Print Report
            </Button>
          </div>
        }
      />

      <div className="resumate-card" style={{ marginBottom: '24px' }}>
        <div className="card-header">
          <div>
            <h2 style={{ fontSize: 'var(--font-xl)', color: 'var(--color-text-main)' }}>
              Candidate Resume Dossier
            </h2>
            <p style={{ fontSize: 'var(--font-xs)', color: 'var(--color-text-muted)', marginTop: '2px' }}>
              Generated by ResuMate AI • Document: {resumeFile?.name || 'Raw Text Resume'}
            </p>
          </div>
          <span className="badge badge-primary">ResuMate AI Certified</span>
        </div>

        {/* Section 1: Executive Summary & Scores */}
        <div className="grid-3" style={{ marginBottom: '24px' }}>
          <div style={{ padding: '16px', borderRadius: 'var(--radius-md)', backgroundColor: 'var(--color-bg)' }}>
            <span style={{ fontSize: 'var(--font-xs)', color: 'var(--color-text-muted)' }}>ATS Score</span>
            <div style={{ fontSize: '32px', fontWeight: 700, color: 'var(--color-primary)' }}>
              {analysisResults?.atsScore ? `${analysisResults.atsScore}/100` : 'Pending'}
            </div>
          </div>

          <div style={{ padding: '16px', borderRadius: 'var(--radius-md)', backgroundColor: 'var(--color-bg)' }}>
            <span style={{ fontSize: 'var(--font-xs)', color: 'var(--color-text-muted)' }}>Job Match Fit</span>
            <div style={{ fontSize: '32px', fontWeight: 700, color: 'var(--color-secondary)' }}>
              {matchingResults?.matchPercentage ? `${matchingResults.matchPercentage}%` : 'Pending'}
            </div>
          </div>

          <div style={{ padding: '16px', borderRadius: 'var(--radius-md)', backgroundColor: 'var(--color-bg)' }}>
            <span style={{ fontSize: 'var(--font-xs)', color: 'var(--color-text-muted)' }}>Skill Readiness</span>
            <div style={{ fontSize: '32px', fontWeight: 700, color: 'var(--color-success)' }}>
              {skillAnalysisResults?.readinessScore ? `${skillAnalysisResults.readinessScore}%` : 'Pending'}
            </div>
          </div>
        </div>

        {/* Section 2: Candidate Summary */}
        {analysisResults?.summary && (
          <div style={{ marginBottom: '24px' }}>
            <h3 style={{ fontSize: 'var(--font-md)', marginBottom: '8px' }}>Executive Summary</h3>
            <p style={{ fontSize: 'var(--font-sm)', lineHeight: '1.7' }}>{analysisResults.summary}</p>
          </div>
        )}

        {/* Section 3: Strengths and Weaknesses */}
        {analysisResults && (
          <div className="grid-2" style={{ marginBottom: '24px' }}>
            <div>
              <h4 style={{ fontSize: 'var(--font-sm)', color: 'var(--color-success)', marginBottom: '8px' }}>
                Key Strengths Identified
              </h4>
              <ul style={{ paddingLeft: '18px', fontSize: 'var(--font-xs)', display: 'flex', flexDirection: 'column', gap: '4px' }}>
                {(analysisResults.keyStrengths || []).map((s, idx) => (
                  <li key={idx}>{s}</li>
                ))}
              </ul>
            </div>

            <div>
              <h4 style={{ fontSize: 'var(--font-sm)', color: 'var(--color-danger)', marginBottom: '8px' }}>
                Critical Areas for Improvement
              </h4>
              <ul style={{ paddingLeft: '18px', fontSize: 'var(--font-xs)', display: 'flex', flexDirection: 'column', gap: '4px' }}>
                {(analysisResults.criticalWeaknesses || []).map((w, idx) => (
                  <li key={idx}>{w}</li>
                ))}
              </ul>
            </div>
          </div>
        )}

        {/* Section 4: Missing Skills */}
        {skillAnalysisResults?.missingCriticalSkills && (
          <div style={{ marginBottom: '24px' }}>
            <h4 style={{ fontSize: 'var(--font-sm)', color: 'var(--color-warning)', marginBottom: '8px' }}>
              Missing Critical Proficiencies
            </h4>
            <div style={{ display: 'flex', flexWrap: 'wrap', gap: '6px' }}>
              {skillAnalysisResults.missingCriticalSkills.map((sk, idx) => (
                <span key={idx} className="badge badge-warning">
                  {sk}
                </span>
              ))}
            </div>
          </div>
        )}
      </div>

      {/* Developer Guidance Card */}
      <div className="dev-guidance-card">
        <div className="dev-guidance-header">
          <span className="dev-guidance-title">
            <Code2 size={16} /> Module 7: Reports Integration Notes
          </span>
          <span className="badge badge-primary">Module 7</span>
        </div>
        <ul className="dev-guidance-list">
          <li>Gathers outputs from all modules to form a clean, printable summary.</li>
          <li>Can be expanded with html2pdf or jsPDF for custom PDF downloads.</li>
        </ul>
      </div>
    </div>
  );
};

export default ReportsPage;
